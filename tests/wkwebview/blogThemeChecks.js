import { EditorSelection } from '@codemirror/state';
import { SearchQuery, setSearchQuery, openSearchPanel, closeSearchPanel } from '@codemirror/search';

export async function checkThemes({ check, until, tick, view, request, writeTheme, changed, originalTheme, confirmations, confirmationAnswers }) {
  const panel = () => document.querySelector('.blog-themes');
  const select = () => panel().querySelector('select');
  const ready = () => panel()?.getAttribute('aria-busy') === 'false' && !select()?.disabled;
  const current = () => panel().querySelector('output')?.textContent.trim();
  const host = document.querySelector('.editor-host'), content = view.contentDOM;
  const apply = async (preset, name) => {
    select().value = preset;
    select().dispatchEvent(new Event('change', { bubbles: true }));
    await tick();
    panel().querySelector('button').click();
    await until(() => ready() && current() === `現在のテーマ ${name}`);
  };
  const before = view.state.doc.toString();
  await until(ready);
  check('設定に4つの同梱テーマを置く', [...select().options].map(option => option.textContent).join(',') === '標準,モノクロ,和紙,夕闇');
  select().value = 'mono';
  select().dispatchEvent(new Event('change', { bubbles: true }));
  await tick();
  confirmationAnswers.push(false);
  panel().querySelector('button').click();
  await until(ready);
  check('適用の確認を取り消すとtheme.cssと履歴を変えない', (await request({ action: 'read' })).preset === 'standard' && !(await request({ action: 'read' })).history.length);
  await apply('mono', 'モノクロ');
  await until(() => getComputedStyle(content).color === 'rgb(27, 27, 27)');
  check('同梱テーマの適用で本文の色がすぐ変わる', getComputedStyle(host).backgroundColor === 'rgb(255, 255, 255)');
  await apply('washi', '和紙');
  await until(() => getComputedStyle(content).color === 'rgb(42, 36, 32)');
  await until(() => host.querySelector('.article-header h1'));
  check('和紙の本文と見出しをZen Old Minchoに揃える', getComputedStyle(view.scrollDOM).fontFamily.includes('Zen Old Mincho') && getComputedStyle(host.querySelector('.article-header h1')).fontFamily === getComputedStyle(view.scrollDOM).fontFamily);
  await apply('dusk', '夕闇');
  await until(() => getComputedStyle(content).color === 'rgb(237, 229, 220)');
  check('夕闇では本文の欄も暗くなる', getComputedStyle(host).backgroundColor === 'rgb(22, 19, 26)' && getComputedStyle(host).colorScheme === 'dark');
  await until(() => host.querySelector('.article-header h1'));
  check('夕闇の本文と見出しをZen Kaku Gothic Newに揃える', getComputedStyle(view.scrollDOM).fontFamily.includes('Zen Kaku Gothic New') && getComputedStyle(host.querySelector('.article-header h1')).fontFamily === getComputedStyle(view.scrollDOM).fontFamily);
  check('夕闇が左右の欄へ広がらない', getComputedStyle(document.querySelector('.sidebar')).backgroundColor === 'rgb(19, 32, 49)');
  const savedSelection = view.state.selection;
  const text = before.slice(before.indexOf('\n\n') + 2).match(/[ぁ-んァ-ヶ一-龠]{2,}/)?.[0] ?? 'title';
  const from = before.lastIndexOf(text);
  // 検索欄を開いている時だけCodeMirrorが一致箇所の装飾を描く。
  openSearchPanel(view);
  view.dispatch({ selection: EditorSelection.range(from, from + text.length), effects: setSearchQuery.of(new SearchQuery({ search: text })), scrollIntoView: true });
  await tick();
  await until(() => document.querySelector('.cm-searchMatch'));
  const mark = document.querySelector('.cm-searchMatch');
  check('夕闇の検索は暗い背景上に差し色の枠と文字を表示する', getComputedStyle(mark).outlineStyle === 'solid' && getComputedStyle(mark).color === 'rgb(237, 229, 220)');
  const selectionSample = document.createElement('span');
  selectionSample.className = 'nagori-selection'; host.append(selectionSample);
  const cursorSample = document.createElement('span');
  cursorSample.className = 'cm-cursor'; host.append(cursorSample);
  check('夕闇のカーソルと選択範囲が背景と区別できる', getComputedStyle(cursorSample).borderLeftColor === 'rgb(237, 229, 220)' && getComputedStyle(selectionSample).backgroundColor !== getComputedStyle(host).backgroundColor && getComputedStyle(selectionSample).backgroundColor !== 'rgba(0, 0, 0, 0)');
  selectionSample.remove(); cursorSample.remove();
  view.dispatch({ selection: savedSelection, effects: setSearchQuery.of(new SearchQuery({ search: '' })) });
  closeSearchPanel(view);
  const state = await request({ action: 'read' });
  check('適用前のテーマを日時付きでブログの外に残す', state.history.length === 3 && state.history.every(entry => entry.savedAt > 0));
  panel().querySelector('.theme-history').open = true;
  const standard = [...panel().querySelectorAll('.theme-history li')].find(row => row.querySelector('span').textContent === '標準');
  standard.querySelector('button').click();
  await until(() => ready() && current() === '現在のテーマ 標準');
  await until(() => getComputedStyle(content).color === 'rgb(30, 42, 63)');
  check('履歴から戻すと本文も戻り、直前の夕闇を履歴に残す', (await request({ action: 'read' })).history[0].preset === 'dusk');
  const customCss = originalTheme.theme + '\n/* カスタムの確認 */\n';
  await writeTheme('src/theme/theme.css', customCss);
  changed('src/theme/theme.css');
  await until(() => ready() && current() === '現在のテーマ カスタム1');
  check('カスタムを自動保存し基本テーマの後ろへ並べる', [...select().options].map(option => option.textContent).join(',') === '標準,モノクロ,和紙,夕闇,カスタム1');
  const reopen = async () => {
    document.querySelector('[aria-label="設定を閉じる"]').click();
    await until(() => !document.querySelector('.settings-dialog[open]') && document.querySelector('.settings-button').getAttribute('aria-expanded') === 'false');
    document.querySelector('.settings-button').click();
    await until(() => document.querySelector('.settings-dialog[open]') && ready());
  };
  await reopen();
  check('同じカスタムで設定を開き直しても重複しない', (await request({ action: 'read' })).customs.length === 1 && current() === '現在のテーマ カスタム1');
  await apply('mono', 'モノクロ');
  await apply('custom-1', 'カスタム1');
  await until(() => getComputedStyle(content).color === 'rgb(30, 42, 63)');
  check('保存したカスタムを一覧から適用して戻せる', (await (await fetch('./blog-theme')).json()).theme === customCss);
  await writeTheme('src/theme/theme.css', originalTheme.theme + '\n:root { --color-text: #643219; }\n');
  changed('src/theme/theme.css');
  await until(() => ready() && current() === '現在のテーマ カスタム2');
  await apply('custom-1', 'カスタム1');
  const customHistory = [...panel().querySelectorAll('.theme-history li')].find(row => row.querySelector('span').textContent === 'カスタム2');
  customHistory.querySelector('button').click();
  await until(() => ready() && current() === '現在のテーマ カスタム2');
  await until(() => getComputedStyle(content).color === 'rgb(100, 50, 25)');
  check('カスタムの履歴から戻しても保存した名前を表示する', current() === '現在のテーマ カスタム2');
  await apply('custom-1', 'カスタム1');
  const remove = name => [...panel().querySelectorAll('.custom-themes li')].find(row => row.querySelector('span').textContent === name).querySelector('button').click();
  panel().querySelector('.custom-themes').open = true;
  confirmationAnswers.push(false);
  remove('カスタム2');
  await until(ready);
  check('カスタムの削除の確認を取り消すと残る', (await request({ action: 'read' })).customs.length === 2);
  remove('カスタム2');
  await until(() => ready() && ![...select().options].some(option => option.value === 'custom-2'));
  remove('カスタム1');
  await until(() => ready() && current() === '現在のテーマ 未登録');
  check('使用中のカスタムを削除してもtheme.cssを変えない', (await (await fetch('./blog-theme')).json()).theme === customCss && ![...select().options].some(option => option.value.startsWith('custom-')));
  await reopen();
  await until(() => current() === '現在のテーマ カスタム3');
  check('削除した番号は使い回さず設定を開いた時に保存する', select().selectedOptions[0].textContent === 'カスタム3' && confirmations.some(message => message.includes('「カスタム1」を削除')));
  // 確認ダイアログの直前に外で変える。画面が持つ古い基準では上書きできない。
  await writeTheme('src/theme/theme.css', originalTheme.theme + '\n/* 外で変更 */\n');
  select().value = 'mono'; select().dispatchEvent(new Event('change', { bubbles: true }));
  await tick();
  panel().querySelector('button').click();
  await until(() => panel().querySelector('[role="alert"]'));
  check('外の変更とぶつかった時は知らせて上書きしない', panel().querySelector('[role="alert"]').textContent.includes('ディスクの内容が変更') && (await request({ action: 'read' })).preset === null);
  [...panel().querySelectorAll('button')].find(button => button.textContent === '再読み込み').click();
  await until(() => ready() && !panel().querySelector('[role="alert"]'));
  check('再読み込みした別のカスタムにも次の番号を付ける', current() === '現在のテーマ カスタム4');
  await apply('standard', '標準');
  await until(() => getComputedStyle(content).color === 'rgb(30, 42, 63)');
  check('適用と復元は確認を出し、記事の本文を保つ', confirmations.some(message => message.includes('theme.cssを置き換え')) && confirmations.some(message => message.includes('履歴のtheme.cssに戻')) && view.state.doc.toString() === before);
}
